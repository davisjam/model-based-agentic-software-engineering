"""ONE residual-notation scan, read over EVERY rendered surface the book emits.

WHY THIS MODULE EXISTS — a resolver cannot report a call it never received. `build_book._apply_metrics`
fails loud on an UNKNOWN token, which is why a typo stops the build; it is structurally blind to a KNOWN
token on a surface that never invoked it. Measured 261106: the appendix path composed its own partial token
chain, so `{{commits_per_week}}` shipped as literal braces to the published evidence-ledger page while the
print surface rendered `1,000`. Fail-loud gave no coverage guarantee at all — only a per-surface scan of the
emitted bytes does, and the scan that existed read the WEB projection alone.

So the surface roster is DECLARED here (`SURFACES`), one row per rendered artifact, and the discriminators
are written ONCE and applied to every row. Three copies of the scan, one per emitter, is the shape this
module exists to refuse: the third copy is where the next omission hides. (Peers: `tools/pruned_walk.py`
and `build_book.apply_token_passes` — one walker, one resolver, every caller.)

THE ROSTER IS THE COVERAGE CLAIM. Every run prints one line per declared surface — either the file count it
scanned or why it could not — because an undeclared exclusion and a forgotten one look identical from a
script list, and this repo has paid for that confusion before. A surface that cannot be read names the
command that emits it rather than disappearing from the output.

THE DISCRIMINATORS are keyword-scoped on purpose, not a blunt `<!--` / `{{` / `[+` sweep (legitimate SVG
structure comments, `<!-- noqa … -->`, the `GENERATED by catalog.py` banner, and prose that SHOWS template
syntax must not false-positive):

  * MARKER  — a marker comment for a KNOWN `build_book.MARKER_KEYWORDS` keyword, escaped (`&lt;!-- gloss …`)
    or raw (`<!-- figure: …`). The keyword + boundary anchor is what excludes the banner and noqa comments.
  * TOKEN   — an unresolved `{{name}}` / `{{part:N}}`. The build fails loud on an unknown token, so any
    survivor means a token slipped a fence and shipped literally.
  * EMPH    — a leaked intra-word-emphasis span `[+X+]`; the build converts these to emphasis, so a
    survivor is raw notation a reader sees.

Standalone report over every surface (the shape to run after a `--pdf` build):
`python3 -m tests.notation_leak` — a package module, so the `-m` form is the invocation.

ARMS ARE PER-SURFACE, and the omissions are declared rather than inferred — each one because that surface
legitimately CARRIES the notation at the stage it is read, not because the arm is inconvenient:

  * `book/latex/build/*.md` is the PRE-pandoc intermediate, and `mage_latex._prepare_record` writes
    `<!-- chapter-title: … -->` into it itself plus an injected `<!-- latex-index-anchor: … -->`. Marker
    comments are expected there BY CONSTRUCTION, so MARKER would false-positive on every chapter. EMPH
    holds, because that same function converts `[+X+]` before writing the file.
  * the stapled review markdown prints the IR's raw blocks VERBATIM and renders no inline markup, so BOTH
    MARKER and EMPH ride along legitimately. Only TOKEN applies there.

TOKEN holds on EVERY surface, because every one of them is downstream of `apply_token_passes` and no stage
legitimately carries an unresolved `{{token}}`. That is the arm the 261106 leak needed.
"""
from __future__ import annotations

import os
import re
import sys as _sys
import zipfile
from typing import Callable, NamedTuple

from tests.common import FAIL, PASS, SKIP, ROOT, book_body_files, html_files, rel

# ── The three discriminators, written once ────────────────────────────────────────────────────────────

MARKER, TOKEN, EMPH = "marker", "token", "emph"
ALL_ARMS: tuple[str, ...] = (MARKER, TOKEN, EMPH)

_TOKEN_RE = re.compile(r"\{\{\s*(?:part:\d+|[a-z_][a-z0-9_]*)\s*\}\}")
_EMPH_RE = re.compile(r"\[\+[^\]]+\+\]")


def marker_keywords() -> tuple[str, ...]:
    """The build-time notation vocabulary — READ from its single source of truth in the build script
    (`build_book.MARKER_KEYWORDS`) so this scan can never drift from what the build defines. A new notation
    added there auto-extends every surface's MARKER arm; there is NO second hand-maintained copy (rule #33:
    a stable check that reads the SSOT beats N hand-rolled lints)."""
    book_dir = os.path.join(ROOT, "book")
    if book_dir not in _sys.path:
        _sys.path.insert(0, book_dir)
    import build_book as bb  # noqa: E402 — path set above; the build owns the vocabulary
    return tuple(bb.MARKER_KEYWORDS)


def _marker_re() -> "re.Pattern[str]":
    kws = marker_keywords()
    if not kws:
        raise RuntimeError("build_book.MARKER_KEYWORDS is empty — the vocabulary SSOT vanished")
    alt = "|".join(re.escape(k) for k in kws)
    # The trailing boundary (`:` arg-marker, or `-->`/whitespace for the arg-less `glossary-auto`) keeps the
    # match tight to the vocabulary and off same-prefixed prose.
    esc = rf"&lt;!--\s*(?:{alt})(?:\s*:|\s+|&gt;|--&gt;)"
    raw = rf"<!--\s*(?:{alt})(?:\s*:|\s+|-->)"
    return re.compile(f"(?:{esc})|(?:{raw})")


# ── Per-surface text normalization ────────────────────────────────────────────────────────────────────

_SVG_RE = re.compile(r"<svg\b.*?</svg>", re.S | re.I)

#: LaTeX spellings pandoc emits for the characters the notation vocabulary is built from. Without these the
#: print-LaTeX surface is scanned blind: a leaked `{{commits_per_week}}` reaches the `.tex` as
#: `\{\{commits\_per\_week\}\}` and a leaked `[+X+]` as `{[}+X+{]}`, neither of which the plain patterns see.
_LATEX_SPELLINGS = ((r"\{", "{"), (r"\}", "}"), ("{[}", "["), ("{]}", "]"),
                    (r"\_", "_"), (r"\%", "%"), (r"\&", "&"), (r"\#", "#"))

#: An UNESCAPED `%` opens a LaTeX comment, so the rest of that line is never set. Same predicate the
#: sibling source-side lint uses (`book-models/lint_governed_literal_leak.py`), and the same ordering
#: constraint: comment-stripping keys off an unescaped `%`, so it must run BEFORE the `\%` unescape.
_LATEX_COMMENT_RE = re.compile(r"(?<!\\)%.*$", re.M)


def strip_svg(text: str) -> str:
    """Drop inlined figure SVG. Figure SVGs carry legitimate structure comments (`<!-- takeaway strip -->`)
    that collide with marker-vocabulary keywords once the vocabulary grows; those are figure-authoring
    artifacts, NOT un-rendered PROSE notation — the class this scan guards. Safe because a prose-notation
    leak never lives inside `<svg>`."""
    return _SVG_RE.sub("", text)


def latex_to_scannable(text: str) -> str:
    """One built `.tex` chapter, reduced to the text LuaLaTeX will SET.

    Two steps, and the order is load-bearing. First drop LaTeX comments: pandoc writes every raw-HTML
    block as a `%`-prefixed line, so EVERY authored marker comment reaches the `.tex` as
    `% <!-- gloss-only: … -->` and is never typeset — measured 261106, 0 marker strings in the rendered
    654-page PDF against hundreds in the `.tex`. Keeping the MARKER arm live over the stripped text is
    strictly stronger than declaring the arm out, because it still catches the case that MATTERS: a marker
    that escapes into body text, where the reader would see it.

    Then un-spell the escapes, so the token and emphasis patterns can see their own characters."""
    text = _LATEX_COMMENT_RE.sub("", text)
    for escaped, plain in _LATEX_SPELLINGS:
        text = text.replace(escaped, plain)
    return text


def identity(text: str) -> str:
    return text


# ── The declared surface roster ───────────────────────────────────────────────────────────────────────


class Chunk(NamedTuple):
    """One readable unit of one surface: `label` is what a finding cites (a repo-relative path, or
    `archive!member` for a zip member)."""
    surface: str
    label: str
    text: str


class Surface(NamedTuple):
    name: str
    what: str                                   # what a reader sees through it
    emitted_by: str                             # the command that writes it — `scan` appends it to any
    #                                             absent-reason, so the row declares it ONCE and no reader
    #                                             function re-spells it
    arms: tuple[str, ...]
    normalize: Callable[[str], str]
    read: Callable[[], "tuple[list[Chunk], str | None]"]  # (chunks, absent-reason)


def _read_text_files(surface: str, paths: "list[str]", absent: str) -> "tuple[list[Chunk], str | None]":
    if not paths:
        return [], absent
    return ([Chunk(surface, rel(p), open(p, encoding="utf-8").read()) for p in paths], None)


def _web_site() -> "tuple[list[Chunk], str | None]":
    return _read_text_files("web-site", html_files(), "no built site HTML found")


def _web_book() -> "tuple[list[Chunk], str | None]":
    return _read_text_files("web-book", book_body_files(), "book/web/docs/ not emitted")


def _glob_build(ext: str) -> "list[str]":
    d = os.path.join(ROOT, "book", "latex", "build")
    if not os.path.isdir(d):
        return []
    return sorted(os.path.join(d, f) for f in os.listdir(d) if f.endswith(ext))


def _print_md() -> "tuple[list[Chunk], str | None]":
    return _read_text_files("print-md", _glob_build(".md"),
                            "book/latex/build/*.md not emitted (gitignored)")


def _print_tex() -> "tuple[list[Chunk], str | None]":
    return _read_text_files("print-tex", _glob_build(".tex"),
                            "book/latex/build/*.tex not emitted (gitignored; needs pandoc)")


def _staple() -> "tuple[list[Chunk], str | None]":
    p = os.path.join(ROOT, "book", "dist", "mage-book-stapled.md")
    return _read_text_files("staple", [p] if os.path.isfile(p) else [],
                            "book/dist/mage-book-stapled.md not emitted (gitignored, local-only, "
                            "skipped under CI)")


def _epub() -> "tuple[list[Chunk], str | None]":
    """The EPUB is a zip; read its XHTML members in place rather than unpacking, so the scan grades the
    published bytes and not a copy of them."""
    p = os.path.join(ROOT, "book", "mage-book.epub")
    if not os.path.isfile(p):
        return [], "book/mage-book.epub not emitted (gitignored)"
    chunks: "list[Chunk]" = []
    with zipfile.ZipFile(p) as z:
        for name in sorted(z.namelist()):
            if name.endswith((".xhtml", ".html")):
                chunks.append(Chunk("epub", f"book/mage-book.epub!{name}",
                                    z.read(name).decode("utf-8", "replace")))
    if not chunks:
        return [], "book/mage-book.epub carries no XHTML member — the EPUB is malformed, not merely absent"
    return chunks, None


#: EVERY surface that renders authored book prose. Adding an emitter means adding a row here — the roster is
#: the coverage claim, and a surface missing from it is a silent hole.
#:
#: WHAT IS DELIBERATELY NOT HERE, named because an undeclared exclusion and a forgotten one look identical
#: (measured over the gitignored emitted trees, 261106):
#:   * the course's `{mage:N.M}` readings tokens — a DIFFERENT vocabulary with its own gate
#:     (`tests/course.py: check_course_mage_tokens_resolve`); the handbook carries no `{{token}}` at all.
#:   * `book/mage-*-style.md` (the writing/drawing/presenting style exports) — emitted prose, but copies of
#:     the plugin skill files, which carry ZERO `{{` between them. Not book prose; nothing to resolve.
#:   * `book/_typst/`, `book/_print/`, `book/_pitch/` — legacy/experimental trees with no live emitter.
#:     `book_typst.emit_document` has no caller outside a scratchpad and a worked-examples smoke; the print
#:     edition is LaTeX, so `print-tex` is the print surface.
#:   * the 21 per-section review PDFs — compiled from the SAME `book/latex/build/*.tex` this roster scans,
#:     so a residue in one is a residue in `print-tex` first.
SURFACES: tuple[Surface, ...] = (
    Surface("web-site", "the served catalogue + landing pages", "python3 catalog.py build",
            ALL_ARMS, strip_svg, _web_site),
    Surface("web-book", "the MkDocs book bodies (book/web/docs/<slug>.md)", "python3 book/book_mkdocs.py",
            ALL_ARMS, strip_svg, _web_book),
    # PRE-pandoc intermediate: `mage_latex._prepare_record` writes marker comments into it itself, so the
    # MARKER arm is declared OUT here rather than suppressed per-file.
    Surface("print-md", "the print pipeline's pandoc input", "python3 book/build_book.py --pdf",
            (TOKEN, EMPH), identity, _print_md),
    Surface("print-tex", "the compiled print chapters (what LuaLaTeX sets)",
            "python3 book/build_book.py --pdf", ALL_ARMS, latex_to_scannable, _print_tex),
    Surface("epub", "the published EPUB3 edition's XHTML", "python3 book/book_epub.py",
            ALL_ARMS, strip_svg, _epub),
    # The staple prints the IR's RAW blocks VERBATIM — it renders no inline markup at all, so BOTH
    # rendered-notation arms are declared out: markers ride along, and `[+X+]` is converted at inline-render
    # time (`build_book.inline`), which the staple never reaches. Only TOKEN applies, because `body_md` IS
    # token-resolved, so a `{{token}}` there is a genuine residue. Measured 261106: the manuscript carries
    # ZERO `[+X+]` spans today, so the EMPH arm was green by absence — the first author to use the notation
    # would have turned this row red on legitimate content.
    Surface("staple", "the whole-book stapled review markdown (local aid)",
            "python3 book/build_book.py --pdf", (TOKEN,), identity, _staple),
)

#: The web surfaces, which `tests/html.py: check_no_notation_leak` owns (it pairs them with the source-side
#: AST sole-seam arm). Named rather than pattern-matched so the two registrations cannot silently overlap or
#: silently leave a row ungoverned — `test_notation_leak_partition` holds the split.
WEB_SURFACES: tuple[str, ...] = ("web-site", "web-book")
RENDERED_SURFACES: tuple[str, ...] = ("print-md", "print-tex", "epub", "staple")


# ── The scan ──────────────────────────────────────────────────────────────────────────────────────────


def chunk_findings(chunk: Chunk, arms: "tuple[str, ...]", normalize: Callable[[str], str],
                   marker_re: "re.Pattern[str]") -> "list[str]":
    """Every residue in one chunk, each finding naming the SURFACE and the file — the two facts that turn a
    red gate into a fix, and the two a per-emitter copy of this scan would spell differently each time."""
    text = normalize(chunk.text)
    out: "list[str]" = []
    if MARKER in arms:
        for m in marker_re.finditer(text):
            out.append(f"[{chunk.surface}] {chunk.label}: leaked notation marker "
                       f"{text[m.start():m.start() + 60]!r}")
    if TOKEN in arms:
        for m in _TOKEN_RE.finditer(text):
            out.append(f"[{chunk.surface}] {chunk.label}: unresolved metric token {m.group(0)!r}")
    if EMPH in arms:
        for m in _EMPH_RE.finditer(text):
            out.append(f"[{chunk.surface}] {chunk.label}: leaked intra-word emphasis {m.group(0)!r}")
    return out


def scan(names: "tuple[str, ...]") -> "tuple[list[str], list[str], int]":
    """Scan the named surfaces. Returns `(findings, roster, scanned_surface_count)`.

    `roster` is one line per requested surface: the file count scanned, or why it could not be read and the
    command that emits it. The caller PRINTS the roster whatever the verdict, so coverage is reported rather
    than assumed."""
    marker_re = _marker_re()
    findings: "list[str]" = []
    roster: "list[str]" = []
    scanned = 0
    for s in (s for s in SURFACES if s.name in names):
        chunks, absent = s.read()
        if absent is not None:
            roster.append(f"{s.name}: NOT SCANNED — {absent}; emit with `{s.emitted_by}`")
            continue
        scanned += 1
        for c in chunks:
            findings.extend(chunk_findings(c, s.arms, s.normalize, marker_re))
        omitted = tuple(a for a in ALL_ARMS if a not in s.arms)
        note = f"; {'/'.join(omitted)} arm(s) declared out — see SURFACES" if omitted else ""
        roster.append(f"{s.name}: scanned {len(chunks)} file(s) — {s.what}{note}")
    return findings, roster, scanned


def check_no_notation_leak_rendered_surfaces():
    """BLOCKING: no build-time notation may survive into the PRINT or EPUB editions.

    The sibling web arm lives in `tests/html.py: check_no_notation_leak`, which pairs its scan with the
    source-side AST sole-seam assertion. This covers the surfaces that gate could not see — the print
    pipeline's pandoc input, the compiled LaTeX chapters, the EPUB's XHTML, and the stapled review
    markdown — through the SAME scan, so a notation added to the vocabulary extends both at once.

    These four artifacts are all gitignored and built only by `--pdf` / `book_epub.py`, so the honest
    verdict when none is on disk is SKIP with the emit command named (the posture
    `tests/book.py: check_caption_orphan_gate` already takes for the rendered PDF). Whatever the verdict,
    the roster reports every surface — scanned, or not and why."""
    findings, roster, scanned = scan(RENDERED_SURFACES)
    if findings:
        return FAIL, findings + roster
    return (PASS if scanned else SKIP), roster


def check_notation_leak_surface_selftest():
    """Failure-injection self-test for the per-surface decision seam (`chunk_findings` + each surface's
    normalizer). The four surfaces above are gitignored, so on most trees the live gate SKIPs — a gate that
    skips by default is exactly the kind that rots into a no-op unnoticed. This injects, on synthetic input
    in each surface's WIRE form, the residue that surface would carry, and asserts it is still flagged:

      * the LaTeX wire form (`\\{\\{token\\}\\}`, `{[}+emph+{]}`) — proves `latex_to_scannable` still
        un-spells pandoc's escapes. Without it the print-tex arm reads every chapter and finds nothing.
      * the plain wire form — the print-md / staple / web shape.
      * two NEGATIVES, one per declared arm omission: a `<!-- chapter-title: … -->` on `print-md` (written
        by the emitter itself) and an SVG structure comment on a web surface must stay clean, or the gate
        becomes noise and stops being read."""
    marker_re = _marker_re()
    by_name = {s.name: s for s in SURFACES}
    problems: list[str] = []

    def flagged(surface: str, text: str) -> "list[str]":
        s = by_name[surface]
        return chunk_findings(Chunk(surface, f"synthetic-{surface}", text), s.arms, s.normalize, marker_re)

    kw = marker_keywords()[0]
    cases = (
        ("print-tex", r"A ratio of \{\{support\_ratio\}\} to 1.", "unresolved metric token", True),
        ("print-tex", r"A {[}+run+{]}-time note.", "leaked intra-word emphasis", True),
        ("print-tex", f"<!-- {kw}: x -->", "leaked notation marker", True),
        ("print-md", "A ratio of {{support_ratio}} to 1.", "unresolved metric token", True),
        ("print-md", "A [+run+]-time note.", "leaked intra-word emphasis", True),
        ("epub", "<p>A ratio of {{support_ratio}} to 1.</p>", "unresolved metric token", True),
        ("staple", "A ratio of {{support_ratio}} to 1.", "unresolved metric token", True),
        ("web-book", "<p>A ratio of {{support_ratio}} to 1.</p>", "unresolved metric token", True),
        ("web-book", f"<p>&lt;!-- {kw}: x --&gt;</p>", "leaked notation marker", True),
        # NEGATIVES — the declared arm omissions, the LaTeX comment strip, and the SVG strip. Each pins an
        # omission the manuscript would otherwise trip: the emitter's own `chapter-title`, a marker reaching
        # the `.tex` as a never-typeset `%` comment, the staple's verbatim `[+X+]` (zero in the manuscript
        # today, so nothing but this case would catch the row regressing), and a figure SVG's own comments.
        ("print-md", "<!-- chapter-title: The Printer -->\n\n# The Printer\n", "", False),
        ("print-tex", f"% <!-- {kw}: x -->\n\\chapter*{{The Printer}}\n", "", False),
        ("staple", f"<!-- {kw}: x -->\n\nA [+run+]-time note.\n", "", False),
        ("web-book", f"<svg><!-- {kw}: decorative --></svg>", "", False),
    )
    for surface, text, expect, should_flag in cases:
        hits = flagged(surface, text)
        if should_flag and not hits:
            problems.append(f"{surface}: injected residue {text!r} was NOT flagged — "
                            f"the scan has degraded to a no-op on this surface")
        elif should_flag and expect not in " ".join(hits):
            problems.append(f"{surface}: injected residue {text!r} flagged unexpectedly: {hits!r}")
        elif not should_flag and hits:
            problems.append(f"{surface}: legitimate text {text!r} was flagged (over-fires): {hits!r}")
    return (FAIL if problems else PASS), problems


def check_notation_leak_surface_partition():
    """Every declared surface is owned by exactly one registered gate, and every owned name is declared.

    The two registrations split the roster between them; nothing in Python holds that split, so a surface
    added to `SURFACES` and forgotten in both name tuples would be governed by neither and the output would
    look identical to one deliberately excluded. That is the failure this repo has recorded before, so the
    partition is asserted rather than documented."""
    declared = {s.name for s in SURFACES}
    owned = list(WEB_SURFACES) + list(RENDERED_SURFACES)
    problems: list[str] = []
    problems += [f"surface {n!r} is declared in SURFACES but owned by no gate — "
                 f"add it to WEB_SURFACES or RENDERED_SURFACES" for n in sorted(declared - set(owned))]
    problems += [f"surface {n!r} is owned by a gate but not declared in SURFACES" for n in
                 sorted(set(owned) - declared)]
    problems += [f"surface {n!r} is owned by BOTH gates" for n in sorted({n for n in owned
                                                                          if owned.count(n) > 1})]
    return (FAIL if problems else PASS), problems


def main(argv: "list[str] | None" = None) -> int:
    """Standalone report over EVERY declared surface — the shape an author runs after a `--pdf` build."""
    findings, roster, scanned = scan(tuple(s.name for s in SURFACES))
    print(f"notation-leak: {scanned}/{len(SURFACES)} declared surface(s) scanned")
    for line in roster:
        print(f"  {line}")
    for f in findings:
        print(f"  {f}")
    print(f"notation-leak: {len(findings)} finding(s).")
    return 1 if findings else 0


if __name__ == "__main__":
    raise SystemExit(main())
