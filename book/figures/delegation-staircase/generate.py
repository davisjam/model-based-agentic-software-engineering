#!/usr/bin/env python3
"""Build matching editable SVG/native staircase; fixed geometry encodes qualitative progression.
Hand-controlled geometry is necessary for the stepped accumulation boundary, not a node graph.
"""
from pathlib import Path
from html import escape
R=Path(__file__).resolve().parents[3]
# Top-to-bottom display; the chronology climbs from stage 1 to stage 5.
rows=[
 ('5. ARCHITECT',['System models, traceability,','and controls'],['Residual judgments','and strategy']),
 ('4. TECH LEAD',['Named zones and','boundary rules'],['System map','and strategy']),
 ('3. REVIEW LEAD',['Deterministic checks;','specialized review'],['Unresolved','semantic review']),
 ('2. QA',['Advisory agent review'],['Adjudicate findings']),
 ('1. CO-CODER',['Ordinary repository'],['Read, judge, and','admit changes']),
]
W,H=440,357
# The step widths encode accumulation qualitatively, not measured capability.
points=[(8,38),(88,38),(88,102),(70,102),(70,166),(52,166),(52,230),(34,230),(34,294),(16,294),(16,350),(8,350)]
svg=[f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}pt" height="{H}pt" viewBox="0 0 {W} {H}" role="img" aria-labelledby="title desc" font-family="Source Sans 3, sans-serif">',
 '<title id="title">DocAble’s delegation staircase</title>',
 '<desc id="desc">Five observed stages rise from Co-coder through QA, Review lead, and Tech lead to Architect. The environment accumulates advisory review, deterministic checks, named zones, and system models. Human responsibility shifts from inspecting changes toward unresolved judgments and strategy. The steps are qualitative, not measurements or a prescribed maturity model.</desc>',
 '<rect width="440" height="357" fill="white"/>',
 '<polygon points="'+' '.join(f'{x},{y}' for x,y in points)+'" fill="#e3f0e7"/>']
tex=[r'% Generated by book/figures/delegation-staircase/generate.py; steps are qualitative.',r'\begin{tikzpicture}[x=1bp,y=-1bp,font=\magefigurefont\fontsize{10.5}{12.5}\selectfont]',r'\path[use as bounding box] (0,0) rectangle (440,357);',r'\fill[black!6] '+'--'.join(f'({x},{y})' for x,y in points)+'--cycle;']
def text(x,y,s,bold=False,size=10.5,color='#1c1917'):
 svg.append(f'<text style="font-family: Source Sans 3, sans-serif" font-family="Source Sans 3" x="{x}" y="{y}" font-size="{size}" fill="{color}"'+(' font-weight="700"' if bold else '')+'>'+escape(s)+'</text>')
 st=r'\bfseries ' if bold else ''
 tex.append(r'\node[anchor=base west,inner sep=0bp,outer sep=0bp,font=\magefigurefont\fontsize{'+str(size)+'}{12.5}\\selectfont '+st+'] at ('+str(x)+','+str(y)+') {'+s.replace('&',r'\&')+'};')
text(8,13,'ENVIRONMENT ACCUMULATES',True,11)
text(8,29,'Representation + enforcement',False)
text(298,13,'HUMAN RESPONSIBILITY',True,11)
svg.append('<line x1="290" y1="38" x2="290" y2="350" stroke="#bcb8b2" stroke-width="0.5"/>')
tex.append(r'\draw[black!30,line width=.5bp] (290,38)--(290,350);')
for i,(title,cap,human) in enumerate(rows):
 x=88-18*i;y=38+64*i
 # A thin open shelf replaces the heavy enclosed cards and weight-varying borders.
 svg.append(f'<path d="M{x} {y+56}V{y}H280" fill="none" stroke="#1f7a4d" stroke-width="0.8"/>')
 tex.append(r'\draw[black,line width=.65bp] ('+str(x)+','+str(y+56)+')--('+str(x)+','+str(y)+')--(280,'+str(y)+');')
 text(x+8,y+17,title,True)
 for j,line in enumerate(cap):text(x+8,y+34+12.5*j,line)
 for j,line in enumerate(human):text(298,y+25+12.5*j,line)
svg.append('</svg>');tex.append(r'\end{tikzpicture}')
(R/'book/assets/mage-staircase.svg').write_text('\n'.join(svg)+'\n')
(R/'book/tikz/figures/mage-staircase.tex').write_text('\n'.join(tex)+'\n')
