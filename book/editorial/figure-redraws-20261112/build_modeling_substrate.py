"""Shared-identity traversal, with identical SVG and native TikZ topology.

The author requests an ellipse and separated outbound/return paths, so explicit
vector ports preserve this geometry more faithfully than automatic layout.
"""
from pathlib import Path
from html import escape
ROOT=Path(__file__).resolve().parents[3]
S=['<svg xmlns="http://www.w3.org/2000/svg" width="896" height="620" viewBox="0 0 448 310" role="img" aria-labelledby="title desc">', '<title id="title">Heterogeneous models over shared identities</title>', '<desc id="desc">A service performance question follows the service registry into the shared-identity hub, out to deployment topology, back through the hub, then out to measurements. Four other representations have thin connections to the same hub.</desc>', '<defs><marker id="arrow" markerWidth="7" markerHeight="6" refX="6.8" refY="3" orient="auto" markerUnits="userSpaceOnUse"><path d="M0,0 L7,3 L0,6 Z" fill="black"/></marker></defs>', '<rect width="448" height="310" fill="white"/>']
T=[r'% Generated by build_modeling_substrate.py; all traversals pass through shared identities.',r'\begin{tikzpicture}[x=1bp,y=-1bp,font=\magefigurefont\fontsize{10}{12}\selectfont,>=Latex]']
def text(x,y,lines,bold=False,italic=False):
    lines=lines.split('\n');y0=y-(len(lines)-1)*6
    for i,line in enumerate(lines):
        yy=y0+i*12
        S.append(f'<text x="{x}" y="{yy+3.3}" text-anchor="middle" font-family="&quot;Source Sans 3&quot;, sans-serif" font-size="10" font-weight="{700 if bold else 400}" font-style="{"italic" if italic else "normal"}">{escape(line)}</text>')
        style=(r'\bfseries' if bold else '')+(r'\itshape' if italic else '')
        T.append(r'\node[inner sep=0pt,align=center,font=\magefigurefont\fontsize{10}{12}\selectfont'+style+r'] at ('+f'{x},{yy}'+') {'+line+'};')
def box(x,y,w,h,label,sub=None,bold=False):
    S.append(f'<rect x="{x-w/2}" y="{y-h/2}" width="{w}" height="{h}" rx="3" fill="white" stroke="black" stroke-width=".65"/>')
    T.append(r'\draw[rounded corners=3bp,line width=.65pt,fill=white] ('+f'{x-w/2},{y-h/2}'+') rectangle ('+f'{x+w/2},{y+h/2}'+');')
    text(x,y-(8 if sub else 0),label,bold)
    if sub:text(x,y+13,sub)
def line(start,end):
    S.append(f'<path d="M{start[0]},{start[1]} L{end[0]},{end[1]}" fill="none" stroke="black" stroke-width=".55"/>')
    T.append(r'\draw[line width=.55pt] ('+','.join(map(str,start))+') -- ('+','.join(map(str,end))+');')
def route(start,c1,c2,end):
    points=[start,c1,c2,end]
    S.append('<path d="M'+','.join(map(str,start))+' C'+' '.join(','.join(map(str,p)) for p in [c1,c2,end])+'" fill="none" stroke="black" stroke-width="1.9" marker-end="url(#arrow)"/>')
    T.append(r'\draw[-{Latex[length=7bp,width=6bp]},line width=1.9pt] ('+','.join(map(str,start))+') .. controls ('+','.join(map(str,c1))+') and ('+','.join(map(str,c2))+') .. ('+','.join(map(str,end))+');')
def number(x,y,n):
    S.append(f'<circle cx="{x}" cy="{y}" r="8" fill="white" stroke="black" stroke-width=".7"/>')
    T.append(r'\draw[fill=white,line width=.7pt] ('+f'{x},{y}'+') circle[radius=8bp];');text(x,y,str(n),True)
# Thin spokes indicate other available relationships, without imposing an order.
line((111,103),(135,133));line((111,222),(137,198));line((207,268),(207,218));line((330,74),(265,125))
# Every highlighted transition passes through the hub; the return route is separate.
route((202,56),(202,81),(188,88),(192,113))
route((290,148),(308,141),(315,141),(330,143))
route((330,181),(315,193),(306,192),(290,181))
route((269,203),(287,227),(305,267),(330,278))
# The hub is a semantic join, not an eighth model.
S.append('<ellipse cx="207" cy="165" rx="88" ry="53" fill="#eeeeee" stroke="black" stroke-width=".7"/>')
T.append(r'\draw[line width=.7pt,fill=black!7] (207,165) ellipse[x radius=88bp,y radius=53bp];')
text(207,147,'Traverse via\nshared identities',True)
text(207,179,'e.g., investigate a\nservice’s performance',italic=True)
box(202,32,124,48,'Service registry','(identify service)',True)
box(58,103,106,42,'Provenance\nrecords')
box(58,222,106,42,'Computation\ngraph')
box(207,287,116,38,'Entitlement\npolicy')
