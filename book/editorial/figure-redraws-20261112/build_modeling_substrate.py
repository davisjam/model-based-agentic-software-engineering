box(386,278,112,48,'Measurements','(how it performs)',True)
number(179,84,1);number(312,123,2);number(319,229,3)
S.append('</svg>');T.append(r'\end{tikzpicture}')
(ROOT/'book/assets/modeling-substrate.svg').write_text('\n'.join(S)+'\n')
(ROOT/'book/tikz/figures/modeling-substrate.tex').write_text('\n'.join(T)+'\n')
