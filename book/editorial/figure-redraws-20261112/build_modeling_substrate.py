"""Shared-identity traversal, with identical SVG and native TikZ topology.

The author requests an ellipse and separated outbound/return paths, so explicit
vector ports preserve this geometry more faithfully than automatic layout.
"""
from pathlib import Path
from html import escape
ROOT=Path(__file__).resolve().parents[3]
S=['<svg xmlns="http://www.w3.org/2000/svg" width="670" height="402" viewBox="0 0 335 201" role="img" aria-labelledby="title desc">', '<title id="title">Heterogeneous models over shared identities</title>', '<desc id="desc">A service performance question follows the service registry into the shared-identity hub, out to deployment topology, back through the hub, then out to measurements. Four other representations have thin connections to the same hub.</desc>', '<defs><marker id="arrow" markerWidth="7" markerHeight="6" refX="6.8" refY="3" orient="auto" markerUnits="userSpaceOnUse"><path d="M0,0 L7,3 L0,6 Z" fill="black"/></marker></defs>', '<rect width="335" height="201" fill="white"/>']
T=[r'% Generated by build_modeling_substrate.py; all traversals pass through shared identities.',r'\begin{tikzpicture}[x=1bp,y=-1bp,font=\magefigurefont\fontsize{10}{12}\selectfont,>=Latex]']
def text(x,y,lines,bold=False,italic=False):
    lines=lines.split('\n');y0=y-(len(lines)-1)*6
    for i,line in enumerate(lines):
        yy=y0+i*12
        S.append(f'<text x="{x}" y="{yy+3.3}" text-anchor="middle" font-family="&quot;Source Sans 3&quot;, sans-serif" font-size="10" font-weight="{700 if bold else 400}" font-style="{"italic" if italic else "normal"}">{escape(line)}</text>')
        style=(r'\bfseries' if bold else '')+(r'\itshape' if italic else '')
        T.append(r'\node[inner sep=0pt,align=center,font=\magefigurefont\fontsize{10}{12}\selectfont'+style+r'] at ('+f'{x},{yy}'+') {'+line+'};')
def box(x,y,w,h,label,sub=None,bold=False):
    S.append(f'<rect x="{x-w/2}" y="{y-h/2}" width="{w}" height="{h}" rx="3" fill="white" stroke="black" stroke-width=".65"/>')
    T.append(r'\draw[rounded corners=3bp,line width=.65pt,fill=white] ('+f'{x-w/2},{y-h/2}'+') rectangle ('+f'{x+w/2},{y+h/2}'+');')
    if sub:
        # Center the full label stack, keeping the existing 12 bp line pitch.
        text(x, y - 6, label, bold)
        text(x, y + 6 * len(label.splitlines()), sub)
    else:
        text(x, y, label, bold)
def line(start,end):
    S.append(f'<path d="M{start[0]},{start[1]} L{end[0]},{end[1]}" fill="none" stroke="black" stroke-width=".55"/>')
    T.append(r'\draw[line width=.55pt] ('+','.join(map(str,start))+') -- ('+','.join(map(str,end))+');')
def route(start,c1,c2,end):
    points=[start,c1,c2,end]
    S.append('<path d="M'+','.join(map(str,start))+' C'+' '.join(','.join(map(str,p)) for p in [c1,c2,end])+'" fill="none" stroke="black" stroke-width="1.9" marker-end="url(#arrow)"/>')
    T.append(r'\draw[-{Latex[length=7bp,width=6bp]},line width=1.9pt] ('+','.join(map(str,start))+') .. controls ('+','.join(map(str,c1))+') and ('+','.join(map(str,c2))+') .. ('+','.join(map(str,end))+');')
def number(x,y,n):
    S.append(f'<circle cx="{x}" cy="{y}" r="8" fill="white" stroke="black" stroke-width=".7"/>')
    T.append(r'\draw[fill=white,line width=.7pt] ('+f'{x},{y}'+') circle[radius=8bp];');text(x,y,str(n),True)
# Thin spokes indicate other available relationships, without imposing an order.
line((75,68),(101,85))
line((75,140),(101,123))
line((155,168),(155,138))
line((243,48),(201,80))
# Outbound and return curves use separate ports on the deployment box.
route((151,32),(151,47),(144,56),(145,70))
route((217,94),(227,89),(233,89),(244,92))
route((244,119),(234,126),(224,125),(215,117))
route((199,129),(213,147),(227,169),(243,177))
# The hub is a semantic join, not an eighth model.
S.append('<ellipse cx="155" cy="104" rx="65" ry="34" fill="#eeeeee" stroke="black" stroke-width=".7"/>')
T.append(r'\draw[line width=.7pt,fill=black!7] (155,104) ellipse[x radius=65bp,y radius=34bp];')
text(155,91,'Traverse via\nshared identities',True)
text(155,117,'e.g., investigate a\nservice’s performance',italic=True)
box(151,18,91,28,'Service registry','(identify service)',True)
box(40,68,70,29,'Provenance\nrecords')
box(40,140,70,29,'Computation\ngraph')
box(155,182,74,28,'Entitlement\npolicy')
box(286,48,86,20,'State machines')
box(287,105,86,42,'Deployment\ntopology','(where it runs)',True)
box(287,177,88,30,'Measurements','(how it performs)',True)
number(132,49,1)
number(232,76,2)
number(234,148,3)
S.append('</svg>');T.append(r'\end{tikzpicture}')
(ROOT/'book/assets/modeling-substrate.svg').write_text('\n'.join(S)+'\n')
(ROOT/'book/tikz/figures/modeling-substrate.tex').write_text('\n'.join(T)+'\n')
