def text(x,y,lines,bold=False,italic=False):
    lines=lines.split('\n'); y0=y-(len(lines)-1)*6
    for i,line in enumerate(lines):
        yy=y0+i*12
        S.append(f'<text x="{x}" y="{yy+3.3}" text-anchor="middle" font-family="&quot;Source Sans 3&quot;, sans-serif" font-size="10" font-weight="{700 if bold else 400}" font-style="{"italic" if italic else "normal"}">{escape(line)}</text>')
        style=(r'\bfseries' if bold else '')+(r'\itshape' if italic else '')
        T.append(r'\node[inner sep=0pt,align=center,font=\magefigurefont'+style+r'] at ('+f'{x},{yy}'+r') {'+line.replace('&',r'\&').replace('≈',r'$\approx$')+'};')
def box(x,y,w,h,label,gray=0,bold=False):
    fill=round(255*(1-gray/100));S.append(f'<rect x="{x-w/2}" y="{y-h/2}" width="{w}" height="{h}" rx="3" fill="rgb({fill},{fill},{fill})" stroke="black" stroke-width=".6"/>')
    T.append(r'\draw[rounded corners=3bp,line width=.6pt,fill=black!'+str(gray)+'] ('+f'{x-w/2},{y-h/2}'+') rectangle ('+f'{x+w/2},{y+h/2}'+');');text(x,y,label,bold)
def path(points,arrow=True):
    S.append('<path d="'+' '.join(('M'if i==0 else'L')+f'{x},{y}' for i,(x,y)in enumerate(points))+'" fill="none" stroke="black" stroke-width=".65"'+(' marker-end="url(#arrow)"'if arrow else'')+'/>')
    T.append(r'\draw['+('-Latex,'if arrow else'')+'line width=.65pt] '+' -- '.join(f'({x},{y})' for x,y in points)+';')
def band(x,w,label):
    S.append(f'<rect x="{x}" y="0" width="{w}" height="23" rx="3" fill="#e8e8e8"/>')
    T.append(r'\fill[black!9,rounded corners=3bp] ('+f'{x},0'+') rectangle ('+f'{x+w},23'+');');text(x+w/2,11.5,label,True)

