"""The CHAPTER-SHAPE view — a typed model of each chapter's OPENING and CLOSING shape against the
editorial discipline (directive book/_design/book-editorial-discipline-directive-260802.md Part A Task 2 /
Part B Phase 2). The seventh sibling model beside outline / outcomes / concepts / big-ideas / claims /
argument-spine.

THE DISCIPLINE IT ENCODES.  Every chapter OPENING should identify (1) the failure or question the chapter
addresses, (2) the chapter's answer, and (3) how the chapter advances one of the book's two theses
(Modeling / Alignment) — or, for chapters whose spine labels carry neither thesis directly, its step in the
argument. Every chapter ENDING should be ONE of: a concrete consequence, a transition to the next
unresolved problem, or a concise synthesis — and must NOT merely re-announce the chapter's thesis.

WHY A NEW MODEL, NOT AN EXTENSION.  The outline model is derived from the book on every run — it has no
hand-authored source an editorial judgment could live in. The outcomes model is pedagogical (what the
reader can do), not rhetorical (how the chapter opens and lands). The argument-spine holds WHAT each
chapter advances; this model holds HOW the chapter's first and last prose carry it. Same homing rule that
earned the spine its own file: distinctive fields that belong to no sibling.

JOIN, DON'T RESTATE.  Chapter exemptions (preface / conclusion / discussion / end-of-part-synthesis /
apparatus / overview) are JOINED from the argument-spine's declared source at derive time — a single
source of truth, no second copy. The spine's per-chapter `advances` labels are likewise read live for the
thesis-consistency flag.

ASSESSMENTS ARE HAND-AUTHORED; FLAGS ARE DERIVED.  chapter_shape_declared.json records, per chapter, the
2a editorial assessment: presence of each opening element (explicit / implicit / absent), the thesis the
opening claims (modeling / alignment / both / argument-step / none), the closing's kind, and a short
evidence note. The generator derives the FLAG worklist (never authored, mirroring the spine's focus
flags): a non-exempt chapter whose opening lacks an element outright, whose closing is a bad kind
(apparatus / mid-taxonomy / re-announcement), or whose claimed thesis mismatches its spine labels. Exempt
chapters are assessed but never flagged — softer treatment per the directive.

ANCHORS FREEZE THE ASSESSED PROSE.  Each declared record carries `opening_anchor` / `closing_anchor` — the
first / last words of the prose the assessment was made against. The CS5 staleness check re-derives the
chapter's current opening/closing prose from the book (via book_ir) and fails the anchor when the prose
has changed: a rewritten opening (the Phase-2c refactor) invalidates its assessment loudly instead of
letting the model describe prose that no longer exists. Regenerating the artifact never refreshes an
anchor; only a re-assessment (editing the declared file) does.

Run `python3 book-models/chapter_shape_model.py regenerate` to write chapter-shape.json; `... verify` to
drift-check; `... flags` to print the derived worklist; `... anchors <slug>` to print a chapter's current
anchor words (for re-assessment).
"""
