"""The LEARNING-OUTCOMES view — a typed model of what a reader should be able to DO or KNOW after each
unit of the book, and which unit teaches which outcome. The book's 6th 4+1-style view (DESIGN §2.6).

Kruchten has no analogue: this is a book-specific PEDAGOGICAL view (the book is a textbook, so it is
modeled as one). Quality question: does every teaching unit — book, Part, chapter, and the sampled
sections — declare what a reader should be able to do after it, does that outcome map to a real unit, and
does the Part→chapter→section outcome tree decompose without gaps?

An OUTCOME is an ACTION VERB + OBJECT — "distinguish a constraint from a sensor," "size a transformation to
the model and the guarantee" — pinned to a Bloom cognitive level and to the outline unit that develops it.

THREE-WAY PROVENANCE — honest labeling is the load-bearing rule.  Every outcome carries a `provenance` tag
that says how honestly it reflects the prose AS WRITTEN:
  - `derived`         — grounded in what the unit ACTUALLY teaches, traceable to an anchor (a topic sentence
                        or heading). The "what the book teaches as written" set.
  - `declared`        — a real outcome the existing (sometimes thin) prose roughly supports, made explicit
                        by the author (e.g. a chapter outcome synthesized across its section titles).
  - `gap-recommended` — the outcome a MISSING or inadequately-delivered unit OUGHT to deliver; a
                        recommendation for content that does NOT yet exist. Never masqueraded as derived.
`derived` candidates are lifted mechanically by `_derive_section_candidates()` from verb-led topic sentences;
`declared` and `gap-recommended` outcomes are hand-authored in `outcomes_declared.json` with an `anchor`
(for declared, the grounding prose) or a gap note (for gap-recommended, why the unit falls short). The
declared + gap-recommended sets ARE the author's rearrange/fill worklist. The regen merges: a hand-authored
declaration wins on the units it names; a mechanically-derived candidate fills a section left silent.

NO NEW MARKDOWN SYMBOL.  Outcomes live in this model's `outcomes.json`, keyed by outline section ids — the
renderer stays uncoupled (DESIGN §2.6 "notation decision"). An inline `<!-- outcome: … -->` marker is
*proposed* in DESIGN §3.3 but deliberately NOT wired into the renderer's marker vocabulary here.

Run `python3 book-models/outcomes_model.py regenerate` to write the artifact; `... verify` to drift-check;
`... gaps` to list units with no outcome (the author's rearrange/fill worklist).
"""
