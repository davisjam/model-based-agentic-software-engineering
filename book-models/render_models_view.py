def regenerate() -> int:
    """Render the page and write it to book-models/models-view.html. Returns 0 on success."""
    html_text = render_html()
    with open(OUT_HTML, "w", encoding="utf-8") as fh:
        fh.write(html_text)
    print(f"render_models_view: wrote {os.path.relpath(OUT_HTML, ROOT)} "
          f"({len(html_text):,} bytes)")
    return 0


def verify() -> int:
    """Exit 1 if the committed HTML differs from a fresh render — the freshness contract, callable as a
    standalone gate. The views-audit surfaces the same signal (audit-only-first)."""
    if not os.path.isfile(OUT_HTML):
        print("render_models_view: models-view.html missing — run `regenerate`")
        return 1
    fresh = render_html()
    with open(OUT_HTML, encoding="utf-8") as fh:
        stored = fh.read()
    if fresh != stored:
        print("render_models_view: models-view.html is STALE — run "
              "`python3 book-models/render_models_view.py regenerate`")
        return 1
    print("render_models_view: models-view.html is fresh")
    return 0


def main(argv: list[str]) -> int:
    cmd = argv[0] if argv else "regenerate"
    if cmd in ("regenerate", "render", ""):
        return regenerate()
    if cmd == "verify":
        return verify()
    print(f"usage: {os.path.basename(__file__)} [regenerate|verify]")
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
