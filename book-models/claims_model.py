"""The CLAIMS view — a typed model of the load-bearing PROPOSITIONS and key distinctions the book asserts,
each carrying the AUDIT PREDICATE (`contradicted_by`) that names what prose would negate it. A fifth sibling
model beside outline / outcomes / concepts / big-ideas (DESIGN book/_design/book-claims-model-260801.md).

WHY A NEW MODEL, NOT AN EXTENSION.  The other models hold a term (concepts), a definition, a reader
capability (outcomes), or a fixed landing slot (big-ideas). A claim is none of these: it is a stance the
book TAKES and could silently betray, so it needs the one field none of them carry — `contradicted_by`, the
predicate an audit checks prose against. See DESIGN §1. The claims model reuses the sibling join keys rather
than re-modeling: `asserted_at` / `home` are outline unit keys; `relates_to` links into concepts /
definitions / big-ideas / outcomes. New object, reused keys.

THE JUDGMENT-AUDIT BOUNDARY (load-bearing, DESIGN §4.2).  The contradiction check itself is a SEMANTIC
JUDGMENT-AUDIT owned by a review gate, NOT a blocking lint — no deterministic check separates "keep the
model derived from the code" (a contradiction) from "a derived model kills drift" (a correct use of the same
words). Only the STRUCTURAL / SCHEMA checks here (C1–C6 + the C7-drift freshness check) are mechanical, so
only they may ever go blocking. The watch-phrase surfacing lint (`lint_claim_watch_phrases.py`, C7) stays
AUDIT-ONLY FOREVER — a hit is a review candidate, never a verdict.

TWO-WAY PROVENANCE (DESIGN §3.2).  `stated` — the book asserts it explicitly (`anchor` cites the sentence);
`implicit` — a load-bearing stance the book only implies (`anchor` says why it is not stated outright, the
author's worklist). Never masquerade implicit as stated.

NO NEW MARKDOWN SYMBOL (DESIGN §3.3).  Claims live in this model's `claims.json`, keyed by outline units —
the renderer stays uncoupled. An inline `<!-- claim: <id> -->` marker is a deferred upgrade, not wired here.

Run `python3 book-models/claims_model.py regenerate` to write the artifact; `... verify` to drift-check;
`... claims <chapter>` for the pre-edit consult (the claims a chapter asserts + their contradiction predicates).
"""
