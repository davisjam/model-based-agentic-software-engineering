#!/usr/bin/env python3
"""Generate the Chapter 4 map's SVG and TikZ from one model and canonical titles."""
from pathlib import Path
import argparse
import html
import json
import re
import fitz

ROOT = Path(__file__).resolve().parents[1]
STEM = 'mage-in-practice-map'


def panels(root=ROOT):
    data = json.loads((root / 'book/data/mage-practice-map.json').read_text())
    identities = json.loads((root / 'book-models/chapter_identity_declared.json').read_text())['chapters']
    native = json.loads((root / 'book/latex/native-sources.json').read_text())['sources']
    for row in data['panels']:
        filename = next(x['filename'] for x in identities if x['label'] == row['section'])
        source = next(x['source'] for x in native if x['projection'] == 'book/' + filename)
        title = re.search(r'<!-- chapter-title:\s*(.*?)\s*-->', (root / source).read_text())[1]
        number = re.match(r'(\d+\.\d+)-', Path(filename).name)[1]
        row['heading'] = f'§{number}  {title}'
        row['target'] = Path(filename).stem
    return data['panels']


def render(rows):
    fonts = {k: fitz.Font(fontfile=str(ROOT / 'book/fonts/SourceSans3' / f'SourceSans3-{v}.ttf'))
             for k,v in [('regular','Regular'),('bold','Bold'),('italic','It')]}
    svg = ['<?xml version="1.0" encoding="UTF-8"?>',
        '<svg xmlns="http://www.w3.org/2000/svg" width="400" height="440" viewBox="0 0 400 440" role="img" aria-labelledby="title desc" font-family="Source Sans 3, sans-serif">',
        '<title id="title">MAGE in practice: Chapter 4</title>',
        '<desc id="desc">Four section panels surround a Model, Realize, Evaluate cycle. The panels describe establishing alignment, following engineering questions, recovering existing knowledge, and maintaining the environment. These are related activities, not sequential phases.</desc>',
        '<defs><marker id="arrow" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="6" markerHeight="6" orient="auto"><path d="M0 0 L10 5 L0 10 Z" fill="black"/></marker></defs>']
    tex = [r'% Generated by tools/mage_practice_map.py; do not edit.',
        r'\begin{tikzpicture}[x=1bp,y=-1bp,>=Latex,font=\magefigurefont\fontsize{9.5}{11.5}\selectfont]',r'\hyphenpenalty=10000']
    def box(x,y,w,h,fill='white',radius=4):
        svg.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{radius}" fill="{fill}" stroke="black" stroke-width=".7"/>')
        tex.append(f'\\draw[fill={"black!7" if fill!="white" else "white"},draw=black,line width=.7pt,rounded corners={radius}bp] ({x},{y}) rectangle ({x+w},{y+h});')
    def text(x,y,value,style='regular',center=False,size=9.5):
        attr = ' font-weight="700"' if style=='bold' else ' font-style="italic"' if style=='italic' else ''
        svg.append(f'<text x="{x}" y="{y}" font-size="{size}" text-anchor="{"middle" if center else "start"}"{attr}>{html.escape(value)}</text>')
        escaped=value.replace('&',r'\&').replace('_',r'\_')
        weight=r'\bfseries' if style=='bold' else r'\itshape' if style=='italic' else ''
        tex.append(f'\\node[anchor={"base" if center else "base west"},inner sep=0pt,font=\\magefigurefont\\fontsize{{{size}}}{{11.5}}\\selectfont{weight}] at ({x},{y}) {{{escaped}}};')
    def wrap(value,width,style='regular'):
        lines=['']
        for word in value.split():
            trial=(lines[-1]+' '+word).strip()
            if fonts[style].text_length(trial,fontsize=9.5)>width and lines[-1]:lines.append(word)
            else:lines[-1]=trial
        return lines
    header_height = 35 if any(len(wrap(row['heading'],174,'bold')) > 1 for row in rows) else 24
    panel_height = 130 + header_height - 24
    lower_y = panel_height + 139
    center_y = panel_height + 70
    total_height = 2 * panel_height + 140
    svg[1] = svg[1].replace('440', str(total_height))
    for panel, (row,(x,y)) in enumerate(zip(rows,[(1,1),(207,1),(1,lower_y),(207,lower_y)])):
        # Clip the header fill first, then draw one continuous panel outline.
        svg.append(f'<defs><clipPath id="panel-{panel}"><rect x="{x}" y="{y}" width="192" height="{panel_height}" rx="4"/></clipPath></defs>')
        svg.append(f'<rect x="{x}" y="{y}" width="192" height="{panel_height}" rx="4" fill="white"/>')
        svg.append(f'<rect x="{x}" y="{y}" width="192" height="{header_height}" fill="#eeeeee" clip-path="url(#panel-{panel})"/>')
        svg.append(f'<rect x="{x}" y="{y}" width="192" height="{panel_height}" rx="4" fill="none" stroke="black" stroke-width=".7"/>')
        tex.append(f'\\fill[white,rounded corners=4bp] ({x},{y}) rectangle ({x+192},{y+panel_height});')
        tex.append(r'\begin{scope}')
        tex.append(f'\\clip[rounded corners=4bp] ({x},{y}) rectangle ({x+192},{y+panel_height});')
        tex.append(f'\\fill[black!7] ({x},{y}) rectangle ({x+192},{y+header_height});')
        tex.append(r'\end{scope}')
        tex.append(f'\\draw[black,line width=.7pt,rounded corners=4bp] ({x},{y}) rectangle ({x+192},{y+panel_height});')
        heading=wrap(row['heading'],174,'bold')
        if len(heading)>2:raise ValueError('Section heading needs a larger panel: '+row['heading'])
        for line, offset in zip(heading, [16,27.5]):text(x+9,y+offset,line,'bold')
        lines=wrap(row['intent'],174,'italic'); baseline=y+header_height+15
        for line in lines:text(x+9,baseline,line,'italic');baseline+=11.5
        baseline+=6
        for bullet in row['bullets']:
            text(x+10,baseline,'•')
            for line in wrap(bullet,162):text(x+20,baseline,line);baseline+=11.5
            baseline+=3
        if baseline>y+panel_height:raise ValueError('Panel text exceeds its box: '+row['heading'])
    # The 1.38x cycle has its own clear row; it cannot cover a panel heading.
    scale=1.38
    def point(x,y):return round(200+(x-222)*scale,2),round(center_y+(y-163)*scale,2)
    svg.append(f'<circle cx="200" cy="{center_y}" r="67.62" fill="#f3f3f3" stroke="black" stroke-width=".8"/>')
    tex.append(f'\\draw[fill=black!5,draw=black,line width=.8pt] (200,{center_y}) circle (67.62bp);')
    for path in [
        [(244,131),(266,137),(272,156),(254,173)],
        [(246,193),(238,210),(207,210),(198,193)],
        [(176,181),(168,153),(183,136),(200,131)]]:
        a,b,c,d=[point(*p) for p in path]
        svg.append(f'<path d="M{a[0]} {a[1]} C{b[0]} {b[1]} {c[0]} {c[1]} {d[0]} {d[1]}" fill="none" stroke="black" stroke-width="1.3" marker-end="url(#arrow)"/>')
        tex.append(f'\\draw[-{{Latex[length=5bp,width=4bp]}},line width=1.3pt] {a} .. controls {b} and {c} .. {d};')
    text(200,center_y-9,'MAGE','bold',True,size=11.5)
    text(200,center_y+8,'in Practice','italic',True,size=11.5)
    for x,y,label in [(200,121,'Model'),(224,173,'Realize'),(176,173,'Evaluate')]:
        bx,by=point(x,y)
        box(bx,by,44*scale,20*scale,radius=3)
        text(bx+22*scale,by+18,label,'bold',True,size=11.5)
    svg.append('</svg>');tex.append(r'\end{tikzpicture}')
    return '\n'.join(svg)+'\n','\n'.join(tex)+'\n'


def generate(check=False):
    values=render(panels())
    paths=[ROOT/f'book/assets/{STEM}.svg',ROOT/f'book/tikz/figures/{STEM}.tex']
    for path,value in zip(paths,values):
        if check:
            if not path.exists() or path.read_text()!=value:raise ValueError('Stale chapter map: '+str(path))
        elif not path.exists() or path.read_text()!=value:path.write_text(value)

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true')
    generate(p.parse_args().check)
