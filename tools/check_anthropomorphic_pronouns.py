#!/usr/bin/env python3
"""CHECK `anthropomorphic-pronoun` — an agent or model noun must not take a PERSONAL relative pronoun.

THE POLICY. `plugin/mage/skills/self-communicate/writing/lexicon.md` §"Agent terminology and
anthropomorphism" is the single authoritative home: use *it* / *which* / *that* for an individual agent,
foundation model, or named AI system, never *he* / *she* / *who* / *whom*. This check holds the one half of
that policy a machine can hold without guessing, and it holds it FORWARD: the manuscript is at zero
findings, which is exactly when the check is cheap to land — it lands green and polices the next edit
rather than arriving with a backlog to drain.

THE PATTERN IS NARROW BY CONSTRUCTION, and the narrowness is the whole design. A full audit of the
manuscript (261106, `.scratch/pronoun-audit-261106.md`) scanned `who` / `whom` / `whose` and the
human-gendered pronouns across every authored source: 197 raw hits, triaging to exactly ONE finding
("just me and Claude, WHO produces software far faster than I can inspect", since repaired to *which*).
The gap between 197 and 1 is correct English that must not be touched, in three classes:

  * 46 INTERROGATIVE / noun-clause uses — *"who owns this job"*, *"Who supplies the production system?"*.
    The book's whole ownership vocabulary is built on that question, and it asks about PEOPLE.
  * 36 relative `who` / `whom` with a HUMAN referent — *"the engineers who own the affected code"*,
    *"institutions from whom an account can be demanded"*.
  * 91 `whose`, every one with an inanimate antecedent — *"a model whose inputs are marked"*, *"a control
    whose purpose has disappeared"*. The ordinary possessive relative in English; it personifies nothing.

So the pattern is a system noun with the pronoun ATTACHED (`agent, who` / `model who`), and nothing else.
None of the three classes puts `who` directly after an agent/model noun, so all three are excluded
structurally rather than by an allowlist that would rot. `whose` IS NOT MATCHED AND MUST NOT BE: the
policy's ban list deliberately omits it, the lexicon records why, and a check that flagged it would
commission 91 spurious edits. `\bwhom?\b` cannot match inside *whose* (the `s` denies the word boundary),
so the exclusion is structural too — see `test_anthropomorphic_pronouns.py`, which pins it.

The noun set is `agent` / `foundation model` / `model` / `Claude`, singular and plural. MEASURED on the
current tree: this set reports 0, and so does the audit's singular-only spelling. A WIDER set
(`system`, `tool`, `assistant`, `LLM`, `bot`) was measured too and reports 1 — *"the behavior of its
system, who knew it"*, an interrogative about people. That is the false-positive class this check is built
to avoid, so the wider set is rejected on evidence, not on taste.

IT POLICES THE AUTHORED SOURCE, NOT THE GENERATED PROJECTION (the lesson of `9acaead5a`, which moved the
governed-literal gate off `book/part*/*.md` for the same reason). The manuscript is authored in LaTeX; the
chapter Markdown under `book/part*/` and `book/frontmatter/` is a compatibility view that
`tools/mage_latex.py sync` overwrites, so a finding there names a line nobody can fix in place — and
double-reports every real one. The scanned `.tex` set is therefore DERIVED from
`book/latex/native-sources.json`, the build's own source-versus-projection declaration, so a chapter added
or renamed enters scope with no edit here. Two further AUTHORED surfaces the audit covered are scanned
with it: the hand-authored TikZ figure labels (`book/tikz/figures/*.tex`, minus the 17 that
`tools/mage_tikz_charts.py` generates and stamps with a provenance banner) and the hand-authored
book-models that carry displayed prose. `book-models/metaphor-slogan-index.json` is NOT among them,
though the audit listed it as hand-authored: its own `_provenance` says "GENERATED by
book-models/metaphor_slogan_index_model.py — do not hand-edit".

Usage:
  python3 tools/check_anthropomorphic_pronouns.py            # report; exit 1 on any finding
  python3 tools/check_anthropomorphic_pronouns.py --root DIR # scan a copy of the tree (red/green proofs)
  python3 tools/check_anthropomorphic_pronouns.py --list-scope

Exit codes: 0 = clean; 1 = at least one finding, or a precondition failed (an empty manifest or a declared
source missing from disk, either of which would make a confident zero a lie).
"""
from __future__ import annotations

import argparse
import glob
import json
import os
import re
import sys

_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

#: The build's source-versus-projection declaration, read at check time rather than re-globbed here, so
#: this check and the build cannot disagree about which surface an author edits.
_MANIFEST_REL = os.path.join("book", "latex", "native-sources.json")

#: Hand-authored TikZ figure sources. A figure LABEL is prose a reader sees, and the policy names figure
#: labels explicitly. 17 of these are projections of `tools/mage_tikz_charts.py` and are excluded by their
#: banner (`_GENERATED_BANNER_RE`), not by name — a new generated figure drops out with no edit here.
_FIGURE_GLOB = os.path.join("book", "tikz", "figures", "*.tex")

#: A generator's provenance banner, in the first few non-blank lines of a file it owns. Checked rather
#: than a hardcoded exclusion list, for the same reason the `.tex` set is derived from the manifest.
_GENERATED_BANNER_RE = re.compile(r"\bGENERATED\b|\bgenerated by\b|do not hand-edit", re.I)
_BANNER_SCAN_LINES = 5

#: AUTHORED non-LaTeX surfaces carrying displayed prose, named one by one because `book-models/` holds
#: both authored declarations and generated projections and no mechanical rule separates them cleanly
#: (several of each carry only a `_note`). Each was verified authored before being listed:
#: `figure-caption-tiers.json` declares caption-tier verdicts, `metaphor-spans.json` says "AUTHORED
#: source of truth" in its own `_provenance`, and `book/index-terms.md` is the curated index supplement.
_AUTHORED_EXTRAS = (
    os.path.join("book-models", "figure-caption-tiers.json"),
    os.path.join("book-models", "metaphor-spans.json"),
    os.path.join("book", "index-terms.md"),
)

#: The system nouns, longest spelling first so a finding quotes the fuller noun phrase ("foundation model"
#: rather than "model"). Plural forms are included: the policy's plural bullet asks for *they* / *their*,
#: so "agents who" is the same personification, and the plural spellings measure 0 on the current tree.
_SYSTEM_NOUN = r"foundation\s+models?|agents?|models?|Claude"

#: A system noun with a personal relative pronoun ATTACHED. The gap admits an optional comma (*"just me
#: and Claude, who produces…"* — the one real finding the audit found) and AT MOST ONE newline, never a
#: blank line: a paragraph break is a blank line in LaTeX, and gluing the end of one paragraph to the
#: start of the next would manufacture *"…the agent" / "Who owns this?"* as a finding. The newline arm is
#: pure forward-policing today — these sources are unwrapped, one paragraph per line (longest line 1,890
#: characters) — but a future hard-wrapped paragraph must not open a blind spot.
#:
#: `whom?` CANNOT match inside *whose*: the trailing `s` denies the word boundary. That is the structural
#: exclusion of the 91-occurrence class the policy deliberately does not ban.
_PATTERN = re.compile(
    rf"\b(?:{_SYSTEM_NOUN})\b[ \t]*,?[ \t]*\n?[ \t]*\bwhom?\b", re.I)

#: An unescaped `%` opens a LaTeX comment, whose text does not render…
_TEX_COMMENT_RE = re.compile(r"(?<!\\)%")
#: …EXCEPT the structured decorator comments, whose text DOES render (a `point:` gloss becomes a margin
#: note, a `gloss:` an entry in the book's language section). The policy covers captions and glossary
#: entries, so these are scanned; the metadata comments around them are not.
_TEX_RENDERED_COMMENT_PREFIX = "% <!--"
#: A listing shows text as an EXAMPLE. Blanked for the same reason a code span is.
_TEX_VERBATIM_BEGIN_RE = re.compile(r"\\begin\{(?:verbatim|lstlisting|minted|Verbatim)\}")
_TEX_VERBATIM_END_RE = re.compile(r"\\end\{(?:verbatim|lstlisting|minted|Verbatim)\}")


class PreconditionFailure(Exception):
    """The scanned set cannot be trusted. A confident zero computed over the wrong files is worse than no
    check at all, so the scan refuses rather than reporting clean."""


def native_sources(root: str = _ROOT) -> "list[str]":
    """The declared LaTeX manuscripts, repo-relative and sorted, read from the native-source manifest.

    Fails loud on an empty manifest or a declared source missing from disk: both make the scan narrower
    than it claims to be, and silently."""
    path = os.path.join(root, _MANIFEST_REL)
    try:
        with open(path, encoding="utf-8") as stream:
            rows = json.load(stream)["sources"]
    except (OSError, ValueError, KeyError) as exc:
        raise PreconditionFailure(f"{_MANIFEST_REL} unreadable or malformed ({exc}) — the manifest IS "
                                  "the scanned set, so an unreadable one means the scan is blind") from exc
    sources = sorted({row["source"] for row in rows})
    if not sources:
        raise PreconditionFailure(f"{_MANIFEST_REL} declares no sources — the manifest IS the scanned "
                                  "set, so an empty one means the scan is blind")
    missing = [rel for rel in sources if not os.path.isfile(os.path.join(root, rel))]
    if missing:
        raise PreconditionFailure(
            f"{len(missing)} declared source(s) absent from disk, so they went unscanned: "
            + ", ".join(missing[:5]))
    return sources


def _is_generated(path: str) -> bool:
    """Does this file declare itself a generator's output in its first few non-blank lines?"""
    try:
        with open(path, encoding="utf-8") as stream:
            head = [ln for ln in stream.read().splitlines() if ln.strip()][:_BANNER_SCAN_LINES]
    except OSError:
        return False
    return any(_GENERATED_BANNER_RE.search(ln) for ln in head)


def authored_files(root: str = _ROOT) -> "list[str]":
    """Every AUTHORED prose surface in scope, as sorted repo-relative paths.

    The declared LaTeX manuscripts, the hand-authored TikZ figure labels, and the authored non-LaTeX
    surfaces that carry displayed prose. The generated chapter Markdown is deliberately absent: a finding
    there names a line the next `mage_latex.py sync` overwrites, and double-reports its own source."""
    out = list(native_sources(root))
    for path in sorted(glob.glob(os.path.join(root, _FIGURE_GLOB))):
        if not _is_generated(path):
            out.append(os.path.relpath(path, root))
    out += [rel for rel in _AUTHORED_EXTRAS if os.path.isfile(os.path.join(root, rel))]
    return sorted(set(out))


def _strip_tex_comment(line: str) -> str:
    """Drop a non-rendering LaTeX comment; keep a structured `% <!-- … -->` decorator, whose text renders."""
    match = _TEX_COMMENT_RE.search(line)
    if match is None or line[match.start():].startswith(_TEX_RENDERED_COMMENT_PREFIX):
        return line
    return line[:match.start()]


def scannable_text(rel: str, root: str = _ROOT) -> str:
    """One authored file as the text a reader sees, LINE-FOR-LINE: comments and listing interiors blanked
    rather than removed, so every finding cites the line the author must edit."""
    with open(os.path.join(root, rel), encoding="utf-8") as stream:
        raw = stream.read().splitlines()
    kind = "tex" if rel.endswith(".tex") else ("md" if rel.endswith(".md") else "other")
    out: "list[str]" = []
    in_listing = False
    for line in raw:
        if kind == "tex":
            if _TEX_VERBATIM_BEGIN_RE.search(line):
                in_listing = True
                out.append("")
                continue
            if _TEX_VERBATIM_END_RE.search(line):
                in_listing = False
                out.append("")
                continue
            out.append("" if in_listing else _strip_tex_comment(line))
            continue
        if kind == "md" and line.lstrip().startswith("```"):
            in_listing = not in_listing
            out.append("")
            continue
        out.append("" if in_listing else line)
    return "\n".join(out)


def findings(root: str = _ROOT) -> "list[str]":
    """Every anthropomorphizing relative pronoun attached to a system noun, as `path:line — quote` rows."""
    out: "list[str]" = []
    for rel in authored_files(root):
        text = scannable_text(rel, root)
        for match in _PATTERN.finditer(text):
            line = text.count("\n", 0, match.start()) + 1
            phrase = " ".join(match.group(0).split())
            out.append(f"{rel}:{line} — {phrase!r} personifies a system; the policy asks for "
                       "'it' / 'which' / 'that' (lexicon §'Agent terminology and anthropomorphism')")
    return out


def main(argv: "list[str] | None" = None) -> int:
    parser = argparse.ArgumentParser(description="anthropomorphic-pronoun check over the authored sources.")
    parser.add_argument("--root", default=_ROOT,
                        help="repository root to scan (default: this checkout) — point it at a scratch "
                             "copy to prove the check goes red without editing the live tree")
    parser.add_argument("--list-scope", action="store_true",
                        help="print the authored files in scope and exit")
    args = parser.parse_args(argv)
    try:
        scope = authored_files(args.root)
        if args.list_scope:
            for rel in scope:
                print(rel)
            return 0
        found = findings(args.root)
    except PreconditionFailure as exc:
        print(f"anthropomorphic-pronoun: PRECONDITION FAILED — {exc}", file=sys.stderr)
        return 1
    n_tex = sum(1 for rel in scope if rel.endswith(".tex"))
    print(f"== anthropomorphic-pronoun — no agent/model noun may take a personal relative pronoun "
          f"[BLOCKING] ==\n  scanning {len(scope)} authored file(s) ({n_tex} LaTeX, "
          f"{len(scope) - n_tex} other); the generated chapter Markdown is out of scope by design")
    if not found:
        print("  clean — no agent or model noun takes 'who' / 'whom'")
        return 0
    print(f"  {len(found)} finding(s):")
    for row in found:
        print(f"    {row}")
    return 1


if __name__ == "__main__":
    sys.exit(main())
