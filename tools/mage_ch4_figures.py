"""Compact Chapter 4 figures; shared geometry for SVG and native TikZ."""
from pathlib import Path
from html import escape
import argparse

class Figure:
    def __init__(self,w,h,title,desc):
        self.w,self.h=w,h
        self.s=[f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}" role="img" aria-labelledby="title desc">',f'<title id="title">{escape(title)}</title>',f'<desc id="desc">{escape(desc)}</desc>','<defs><marker id="arrow" markerWidth="5" markerHeight="5" refX="4.5" refY="2.5" orient="auto-start-reverse" markerUnits="userSpaceOnUse"><path d="M0,0 L5,2.5 L0,5 Z" fill="black"/></marker></defs>']
        self.t=[r'% Generated by tools/mage_ch4_figures.py; shared SVG/TikZ geometry.',r'\begin{tikzpicture}[x=1bp,y=-1bp,font=\magefigurefont\fontsize{10}{12}\selectfont,>=Latex]',f'\\path[use as bounding box] (0,0) rectangle ({w},{h});']
    def text(self,x,y,label,size=10,bold=False,italic=False,anchor='middle',rotate=0,ref=None):
        for i,line in enumerate(label.split('\n')):
            yy=y+(i-(len(label.split('\n'))-1)/2)*12
            a=f' font-weight="{700 if bold else 400}" font-style="{"italic" if italic else "normal"}"'
            transform=f' transform="rotate({rotate} {x} {yy})"' if rotate else ''
            txt=f'<text x="{x}" y="{yy+3.3}" text-anchor="{anchor}" font-family="&quot;Source Sans 3&quot;, sans-serif" font-size="{size}"{a}{transform}>{escape(line)}</text>'
            self.s.append(txt)
            val=line.replace('&',r'\&').replace('%',r'\%').replace('_',r'\_').replace('≈',r'$\approx$')
            if ref: val=r'\magebookref{'+ref+'}{'+val+'}'
            self.t.append(r'\node[inner sep=0pt,outer sep=0pt,anchor='+{'middle':'center','start':'west','end':'east'}[anchor]+f',rotate={-rotate},font=\\magefigurefont\\fontsize{{{size}}}{{12}}\\selectfont'+(r'\bfseries' if bold else '')+(r'\itshape' if italic else '')+f'] at ({x},{yy}) {{{val}}};')
    def rect(self,x,y,w,h,gray=0,stroke=True,r=3):
        fill=round(255*(1-gray/100)); col=f'rgb({fill},{fill},{fill})'
        self.s.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{r}" fill="{col}" stroke="{"black" if stroke else "none"}" stroke-width=".65"/>')
        self.t.append(f'\\path[fill=black!{gray},draw={"black" if stroke else "none"},line width=.65bp,rounded corners={r}bp] ({x},{y}) rectangle ({x+w},{y+h});')
    def box(self,x,y,w,h,label,**kw):
        self.rect(x,y,w,h,gray=kw.pop('gray',0));self.text(x+w/2,y+h/2,label,**kw)
    def path(self,pts,arrow=True,both=False,dashed=False):
        self.s.append('<path d="'+' '.join(('M'if i==0 else'L')+f'{x},{y}' for i,(x,y)in enumerate(pts))+'" fill="none" stroke="black" stroke-width=".7"'+(' stroke-dasharray="3 2"'if dashed else'')+(' marker-end="url(#arrow)"'if arrow else'')+(' marker-start="url(#arrow)"'if both else'')+'/>')
        self.t.append(r'\draw['+('<->,'if both else'->,'if arrow else'')+('dashed,'if dashed else'')+'line width=.7bp] '+' -- '.join(f'({x},{y})' for x,y in pts)+';')
    def result(self):return '\n'.join(self.s+['</svg>'])+'\n','\n'.join(self.t+[r'\end{tikzpicture}'])+'\n'

def render_map(rows):
    f=Figure(440,230,'MAGE in practice: Chapter 4','Four section panels surround a compact triangle of Model, Realize, and Evaluate connected in both directions. No starting point or fixed order is prescribed.')
    for row,(x,y) in zip(rows,[(1,1),(227,1),(1,133),(227,133)]):
        f.rect(x,y,212,116 if y==1 else 96)
        f.text(x+10,y+16,row['heading'].replace('  ',' '),size=9.5,bold=True,anchor='start',ref='chapter:'+row['target'])
        for j,line in enumerate(row['bullets']):
            lines=line
            if line=='Modeling before and after realization':lines='Modeling before and after\nrealization'
            if line=='Learning from prediction and measurement':lines='Learning from prediction\nand measurement'
            f.text(x+10,y+39+j*20,lines,size=9.5,anchor='start')
    # The motif occupies the inner corners, not a separate diagram row.
    f.rect(139,91,162,54,stroke=False,r=0)
    f.path([(200,111),(180,124)],both=True);f.path([(240,111),(260,124)],both=True);f.path([(199,133),(241,133)],both=True)
    f.text(220,103,'Model',bold=True,size=11.5)
    f.text(169,133,'Evaluate',bold=True,size=11.5)
    f.text(271,133,'Realize',bold=True,size=11.5)
    return f.result()

